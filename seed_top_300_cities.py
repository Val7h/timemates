def seed_top_300():
    """Insert top 300 cities into the cities table, skipping duplicates by slug."""
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()

    try:
        existing_slugs = {row.slug for row in db.query(City.slug).all()}
        print(f"[INFO] Cities already in DB: {len(existing_slugs)}")

        inserted = 0
        skipped = 0
        for (id_ibge, slug, name, state, population, region, lat, lng, is_capital) in TOP_300_CITIES:
            if slug in existing_slugs:
                skipped += 1
                continue
            city = City(
                slug=slug,
                name=name,
                state=state,
                population=population,
                coordinates={"latitude": lat, "longitude": lng, "ibge_code": id_ibge, "region": region},
            )
            db.add(city)
            inserted += 1

        db.commit()
        print(f"[OK] Inserted {inserted} new cities, skipped {skipped} already-present cities.")
        print(f"[OK] Total cities in DB now: {db.query(City).count()}")
    except Exception as e:
        db.rollback()
        print(f"[ERROR] {e}")
        raise
    finally:
        db.close()


